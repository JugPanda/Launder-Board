import { expect, test } from '@playwright/test';

test('hosted synthetic data, real search, and session events survive refresh without crossing browsers', async ({ page, browser }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('/demo');
  await expect(page.getByLabel('Synthetic profile preview')).toBeVisible();
  await expect(page.getByText(/Supabase profile data/)).toBeVisible();
  await page.getByRole('tab', {name:'Search',exact:true}).click();
  await page.getByRole('searchbox').fill('Rilei');
  await expect(page.getByRole('heading', {name:'Riley',exact:true})).toBeVisible();
  const card = page.locator('article').filter({has:page.getByRole('heading',{name:'Riley',exact:true})});
  await card.getByRole('button').click();
  await expect(page.getByRole('status')).toContainText('Demo nudge saved');
  await page.reload();
  await expect(page.getByLabel('Synthetic profile preview')).toBeVisible();
  await page.getByRole('tab',{name:'Search',exact:true}).click();
  await page.getByRole('searchbox').fill('Riley');
  await expect(page.locator('article').filter({has:page.getByRole('heading',{name:'Riley',exact:true})}).getByRole('button')).toBeDisabled();
  await page.getByRole('tab',{name:'Community',exact:true}).click();
  await page.getByRole('button',{name:/save.*update/i}).click();
  await expect(page.getByRole('status')).toContainText('Preset update saved');
  await page.reload();
  await expect(page.getByLabel('Synthetic profile preview')).toBeVisible();
  await page.getByRole('tab',{name:'Community',exact:true}).click();
  await expect(page.getByText('You, in this demo:',{exact:true})).toBeVisible();
  const own = await page.evaluate(async () => (await fetch('/api/demo/bootstrap', { credentials: 'same-origin', cache: 'no-store' })).json());
  expect(own.nudgedIds).toContain('U003'); expect(own.posts).toHaveLength(1);
  const other = await browser.newContext();
  const isolated = await other.request.get(new URL('/api/demo/bootstrap',page.url()).href);
  const data = await isolated.json(); expect(data.posts).toEqual([]);expect(data.nudgedIds).toEqual([]);
  await other.close();
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Your session events cleared');
  const reset = await page.evaluate(async () => (await fetch('/api/demo/bootstrap', { credentials: 'same-origin', cache: 'no-store' })).json());
  expect(reset.posts).toEqual([]); expect(reset.nudgedIds).toEqual([]);expect(reset.participants).toHaveLength(7);
  expect(errors).toEqual([]);
});
